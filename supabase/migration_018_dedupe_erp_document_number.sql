-- WMS -- Deduplicate erp_document_number: 296 numbers are currently reused
-- across unrelated shipment events (different, unrelated dates), an
-- artifact of the migration_005/010/011/014 "copy tasks into another
-- month" demo-data scripts, which copied erp_document_number verbatim
-- instead of minting a fresh one per copy.
--
-- Confirmed with the user this is internal/demo data with no external
-- ERP/customer link, so renumbering is safe -- no real paperwork, CMR,
-- or customer-facing document references these specific values.
--
-- Why this matters: taskGrouping.ts already works around the reuse by
-- matching each PREP_DRY_ICE to its ERP_DOCUMENT parent by *closest*
-- due_date (see linkPrepDryIce(), which explicitly documents the reuse
-- in a comment). The sync_dry_ice_temperature_group() trigger
-- (migration_016/017) does NOT do this -- it matches by
-- erp_document_number alone, so it can misfire across two unrelated
-- shipments that happen to share a reused number. Eliminating the reuse
-- at the source removes that whole class of bug, instead of teaching
-- every consumer (the trigger, search, future code) to work around it
-- individually.
--
-- Approach: for each reused number, cluster its due_dates -- dates
-- within 3 days of each other are treated as one real shipment event (a
-- PREP_DRY_ICE task is consistently due 1 day before its ERP_DOCUMENT
-- sibling -- confirmed against live data: WMS749370 and WMS757405 each
-- show this exact 1-day offset, independently, 3 times, once per copied
-- month). Anything further apart is a different, unrelated shipment
-- event that happens to reuse the same number.
--
-- The mapping below was computed OFFLINE against a live read-only
-- export of the tasks table, not recomputed in SQL, specifically so its
-- correctness could be reviewed as plain data before running anything --
-- after the migration_016/017 incident, no cleverness runs live and
-- unverified this time. The earliest date-cluster per number keeps its
-- original number unchanged; every later cluster gets one of 345 freshly
-- minted numbers (WMS1000000+, clearly outside the existing 6-digit
-- WMS###### range so old and new numbers stay trivially distinguishable).
--
-- Run in the Supabase SQL Editor after migration_017.

